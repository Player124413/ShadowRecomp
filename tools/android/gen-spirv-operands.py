#!/usr/bin/env python3
"""Writes ShadowRecomp/gpu/spirv_operand_table.inc from the SPIR-V grammar.

    gen-spirv-operands.py <SPIRV-Headers>/include/spirv/unified1/spirv.core.grammar.json

gpu/spirv_int64_lowering.cpp has to tell the ids of an instruction from its literal
numbers. The table says, for every instruction of core SPIR-V, what each operand is:

    T  the id of the result type            R  the id of the result
    i  an id                                l  a literal word
    s  a string                             I  ids up to the end of the instruction
    L  literal words up to the end          g  optional image operands: a mask, then ids
    p  (literal, id) pairs up to the end    q  (id, literal) pairs up to the end
    c  the opcode of a specialization-constant operation, then the operands of that
       operation: ids, a few of them followed by literal indices

Instructions that only extensions define are left out: the pass turns a module down when
it meets one. Run this again only to pick up a newer grammar; the output is committed.
"""

import json
import os
import sys

# The last instruction of core SPIR-V (OpPtrDiff). Above it are extensions.
LAST_CORE_OPCODE = 403

ID_KINDS = {"IdRef", "IdScope", "IdMemorySemantics"}

# What follows the operand decides how the rest of the instruction reads.
REST_OF_INSTRUCTION = {
    "PairIdRefIdRef": "I",
    "PairLiteralIntegerIdRef": "p",
    "PairIdRefLiteralInteger": "q",
    "ImageOperands": "g",
    # A mask, then the literal parameters of the bits that are set. (Ids as parameters
    # only exist for bits that extensions add.)
    "MemoryAccess": "L",
    "LoopControl": "L",
    "LiteralContextDependentNumber": "L",
    "LiteralSpecConstantOpInteger": "c",
}

# Not expressible by the rules below.
OVERRIDES = {
    # Language, version, then an optional id of the file name and an optional string.
    "OpSource": "llL",
}


def pattern(instruction):
    name = instruction["opname"]
    if name in OVERRIDES:
        return OVERRIDES[name]

    result = ""
    operands = instruction.get("operands", [])
    for index, operand in enumerate(operands):
        kind = operand["kind"]
        quantifier = operand.get("quantifier", "")
        rest = operands[index + 1:]

        if kind == "IdResultType":
            result += "T"
        elif kind == "IdResult":
            result += "R"
        elif kind in ID_KINDS:
            if quantifier:
                if any(o["kind"] not in ID_KINDS for o in rest):
                    raise SystemExit(f"{name}: an optional id is followed by something that is not one")
                return result + "I"
            result += "i"
        elif kind in REST_OF_INSTRUCTION:
            return result + REST_OF_INSTRUCTION[kind]
        elif kind in ("Decoration", "ExecutionMode"):
            # The enumerant, then its parameters: ids in the ...Id form of the instruction,
            # literals otherwise.
            return result + ("lI" if name.endswith("Id") else "L")
        elif kind == "LiteralString":
            if quantifier:
                raise SystemExit(f"{name}: an optional string needs an entry in OVERRIDES")
            result += "s"
        else:
            # A literal number or an enumerant without parameters.
            if quantifier:
                if any(o["kind"] in ID_KINDS for o in rest):
                    raise SystemExit(f"{name}: an optional literal is followed by an id")
                return result + "L"
            result += "l"

    return result


def main():
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)

    with open(sys.argv[1], encoding="utf-8") as file:
        grammar = json.load(file)

    patterns = {}
    names = {}
    for instruction in grammar["instructions"]:
        opcode = instruction["opcode"]
        if opcode > LAST_CORE_OPCODE:
            continue
        text = pattern(instruction)
        # Aliases of one opcode must agree.
        if opcode in patterns and patterns[opcode] != text:
            raise SystemExit(f"opcode {opcode} has two different layouts")
        patterns[opcode] = text
        names.setdefault(opcode, instruction["opname"])

    lines = [
        "// Generated by tools/android/gen-spirv-operands.py from spirv.core.grammar.json",
        f"// (SPIR-V {grammar['major_version']}.{grammar['minor_version']}, revision {grammar['revision']}). Do not edit.",
        "//",
        "// One entry per opcode of core SPIR-V: what each operand of the instruction is.",
        "// nullptr: no such instruction.",
    ]
    for opcode in range(LAST_CORE_OPCODE + 1):
        if opcode in patterns:
            lines.append(f'/* {opcode:3} {names[opcode]} */ "{patterns[opcode]}",')
        else:
            lines.append(f"/* {opcode:3} */ nullptr,")

    output = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "ShadowRecomp", "gpu", "spirv_operand_table.inc")
    with open(output, "w", encoding="utf-8", newline="\n") as file:
        file.write("\n".join(lines) + "\n")

    print(f"{len(patterns)} instructions written to {os.path.normpath(output)}")


if __name__ == "__main__":
    main()
